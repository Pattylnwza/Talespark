const background =
    document.getElementById(
        "background"
    );


const chapterTitle =
    document.getElementById(
        "chapterTitle"
    );


const storyText =
    document.getElementById(
        "storyText"
    );


const readBtn =
    document.getElementById(
        "readBtn"
    );


const emotionArea =
    document.getElementById(
        "emotionArea"
    );


const choicesContainer =
    document.getElementById(
        "choices"
    );


const responseBox =
    document.getElementById(
        "responseBox"
    );


const nextBtn =
    document.getElementById(
        "nextBtn"
    );


const endScreen =
    document.getElementById(
        "endScreen"
    );


let currentScene =
    0;


let currentParagraph =
    0;


let selectedChoice =
    null;


let typing =
    false;


let typingTimer =
    null;


let currentText =
    "";


function loadScene(index) {

    currentScene =
        index;

    currentParagraph =
        0;

    selectedChoice =
        null;

    typing =
        false;

    clearInterval(
        typingTimer
    );


    const data =
        story[index];


    changeSceneImage(
        data.scene
    );


    chapterTitle.textContent =
        data.title;


    emotionArea.classList.remove(
        "show"
    );


    storyText.style.display =
        "flex";


    choicesContainer.innerHTML =
        "";


    responseBox.innerHTML =
        "";


    responseBox.classList.remove(
        "show"
    );


    nextBtn.disabled =
        true;

    nextBtn.classList.add(
        "waiting"
    );

    nextBtn.textContent =
        "เลือกความรู้สึกก่อน →";


    readBtn.classList.remove(
        "hidden"
    );


    showParagraph();

}


function showParagraph() {

    const data =
        story[currentScene];


    const paragraph =
        data.paragraphs[
            currentParagraph
        ];


    currentText =
        paragraph;


    typing =
        true;


    clearInterval(
        typingTimer
    );


    storyText.innerHTML =
        '<span></span><span class="typingCursor"></span>';


    const textSpan =
        storyText.querySelector(
            "span"
        );


    let characterIndex =
        0;


    typingTimer =
        setInterval(
            () => {

                if (
                    characterIndex <
                    currentText.length
                ) {

                    textSpan.textContent +=
                        currentText[
                            characterIndex
                        ];

                    characterIndex++;

                }

                else {

                    clearInterval(
                        typingTimer
                    );

                    typing =
                        false;

                    updateReadButton();

                }

            },
            28
        );

}


function handleRead() {

    if (typing) {

        clearInterval(
            typingTimer
        );


        storyText.innerHTML =
            currentText;


        typing =
            false;


        updateReadButton();


        return;
    }


    const data =
        story[currentScene];


    if (
        currentParagraph <
        data.paragraphs.length - 1
    ) {

        currentParagraph++;

        showParagraph();

        return;
    }


    showChoices();

}


function updateReadButton() {

    const data =
        story[currentScene];


    if (typing) {

        readBtn.textContent =
            "แสดงข้อความทั้งหมด";

        return;
    }


    if (
        currentParagraph <
        data.paragraphs.length - 1
    ) {

        readBtn.textContent =
            "อ่านต่อ ▼";

    }

    else {

        readBtn.textContent =
            "เลือกความรู้สึก ▼";

    }

}


function showChoices() {

    const data =
        story[currentScene];


    readBtn.classList.add(
        "hidden"
    );


    emotionArea.classList.add(
        "show"
    );


    choicesContainer.innerHTML =
        "";


    nextBtn.classList.add(
        "waiting"
    );


    nextBtn.disabled =
        true;


    data.choices.forEach(
        (choice, index) => {

            const button =
                document.createElement(
                    "button"
                );


            button.className =
                "choiceBtn";


            button.textContent =
                choice.emotion;


            button.onclick =
                () =>
                    chooseEmotion(
                        index
                    );


            choicesContainer.appendChild(
                button
            );

        }
    );

}


function chooseEmotion(
    choiceIndex
) {

    const data =
        story[currentScene];


    const choice =
        data.choices[
            choiceIndex
        ];


    selectedChoice =
        choiceIndex;


    storyText.style.display =
        "none";


    emotionArea.classList.remove(
        "show"
    );


    changeSceneImage(
        choice.scene
    );


    responseBox.innerHTML =
        `<span class="emotionTag">
            ${choice.emotion}
        </span>
        ${choice.response}`;


    responseBox.classList.add(
        "show"
    );


    nextBtn.disabled =
        false;

    nextBtn.classList.remove(
        "waiting"
    );


    if (
        currentScene ===
        story.length - 1
    ) {

        nextBtn.textContent =
            "จบ Chapter 2 →";

    }

    else {

        nextBtn.textContent =
            "ไปต่อ →";

    }

}


function changeSceneImage(
    imageName
) {

    background.classList.add(
        "scene-change"
    );


    setTimeout(
        () => {

            background.src =
                imageName;

            background.classList.remove(
                "scene-change"
            );

        },
        180
    );

}


function nextStep() {

    if (
        selectedChoice === null
    ) {

        return;
    }


    if (
        currentScene ===
        story.length - 1
    ) {

        endScreen.classList.add(
            "show"
        );

        return;
    }


    loadScene(
        currentScene + 1
    );

}


function goToMinigame2() {
    window.location.href = "../Minigame2/Minigame2.html";
}


function resizeGame() {

    const game = document.getElementById("game");

    const scaleX = window.innerWidth / 1920;
    const scaleY = window.innerHeight / 1080;

    const scale = Math.min(scaleX, scaleY);

    game.style.transform =
        `translate(-50%, -50%) scale(${scale})`;

}

window.addEventListener("resize", resizeGame);

resizeGame();


